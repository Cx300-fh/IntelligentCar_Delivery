/**
 * @file hx711.hpp
 * @brief HX711 称重模块头文件（GPIO软件模拟通信）
 * @details 复用"无刷驱动1/2"接口（本车未使用无刷电机，故借用其两个GPIO）：
 *          - DT (数据)  -> GPIO89 (无刷驱动1 / TIM2_CH3)
 *          - SCK (时钟) -> GPIO77 (无刷驱动2 / I2S_BCLK)
 *          接线: HX711.VCC->3V3, HX711.GND->GND, HX711.DT->GPIO89, HX711.SCK->GPIO77
 *          用万用表核实这两个GPIO在你板子上的实际物理位置后再通电测试。
 *
 * @note    按老师的要求设计：
 *          1. HX711_Init() 只做两件事：初始化GPIO + 去皮，在main的while循环之前调用一次。
 *          2. HX711_Service() 是定时器服务函数，每隔一段时间被 lq_timer 调用一次，
 *             内部不允许出现 delay/usleep，也不允许 while 死等 —— 没转换好就直接返回，
 *             下一次定时器触发时再试，绝不阻塞。
 *
 * @note    屏幕上放4个控件，2静2动：
 *          - "总重量" / "重量变动" : 静态文本标签，HMI设计器里直接打字，代码不管
 *          - t_weight_val (Text)   : 显示总重量，如 "235g"，每次读到新数据都会更新
 *          - t_delta_val  (Text)   : 显示"这一次放入/取出多少"，如 "+235g"/"-80g"，
 *                                    只有在重量变化并重新稳定下来之后才会更新一次
 *          t_weight_val / t_delta_val 这两个名字必须跟HMI里建的控件名一模一样。
 */

#ifndef __HX711_HPP
#define __HX711_HPP

#include "include.hpp"

/*============================================================================
 *                              引脚定义
 *============================================================================*/
#define HX711_SCK_PIN   PIN_77   // 时钟输出（无刷驱动2 / I2S_BCLK 复用口）
#define HX711_DT_PIN    PIN_89   // 数据输入（无刷驱动1 / TIM2_CH3 复用口）

/*============================================================================
 *                              全局变量声明
 *============================================================================*/
extern double hx711_calibration_factor;  // 标定系数（原始值变化量 / 克数），需实测标定
extern long   hx711_offset;              // 去皮偏移量（空载时的原始读数均值）
extern bool   hx711_debug_raw;           // true=每秒打印一次原始值（标定用），标定完置false

extern float  weight_g;                  // 总重量（克），每次成功读数都会更新 -> 发送到屏幕

/*============================================================================
 *                              函数声明
 *============================================================================*/
void HX711_GPIO_Init(void);              // 第1步：只初始化两个GPIO的方向
void HX711_Init(void);                   // 第2步：GPIO初始化 + 去皮 + 启动周期服务定时器（main循环前调用一次）

bool HX711_Is_Ready(void);               // 通信：查询HX711是否转换完成（不等待，立即返回结果）
bool HX711_Read_Raw(long* out_value);    // 通信：非阻塞读取一次24bit原始值；没就绪返回false，不修改out_value

float HX711_Raw_To_Weight(long raw);     // 获取重量：原始值 -> 克数（纯计算，不涉及GPIO）

void HX711_Service(void);                // 定时器服务函数：每次调用最多读一次，内部无delay/while，直接对接屏幕

#endif /* __HX711_HPP */
