/**
 * @file observe.hpp
 * @brief 观测模块头文件
 * @details 调试观测框架：
 *          1. 图传（UDP）
 *          2. FPS 打印（每秒）
 *          3. 实时调试信息
 *          4~5. 串口屏（已移到 screen 模块）
 *          6~7. 语音模块（已移到 voice 模块）
 */

#ifndef __OBSERVE_HPP
#define __OBSERVE_HPP

#include "include.hpp"

/*============================================================================
 *                              FPS 统计变量声明
 *============================================================================*/
extern int fps_observe;     // 观测模块计算的帧率（每秒更新）

/*============================================================================
 *                              函数声明
 *============================================================================*/
// 图传
void Send_Image(uint8_t type);             // 发送图像 (0-不发送, 1-原图, 2-灰度图, 3-二值化图)

// FPS 计算
void Calculate_FPS(void);                  // 计算 FPS（每秒更新 fps_observe 变量，不打印）

// 实时调试信息
void Print_Data(void);                     // 打印数据信息（实时）

/*============================================================================
 *                              图像绘制
 *============================================================================*/
void Draw_RGB(void);                       // 绘制所有可视化内容（边线、Tag等）

#endif /* __OBSERVE_HPP */
